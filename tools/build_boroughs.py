#!/usr/bin/env python3
"""Build common/borough_data.py from an NYC borough boundary GeoJSON.

The GeoJSON is simplified (Douglas-Peucker) so the lookup stays small enough
to ship with every MapReduce task. This script is only needed to regenerate
the data file; the generated file is already included in the project.

Usage: python3 build_boroughs.py boroughs.geojson ../common/borough_data.py
"""
import json
import sys

TOLERANCE = 0.00012      # degrees, roughly 12 m
MIN_RING_AREA = 4e-7     # square degrees, drops specks smaller than ~4,000 m2


def ring_area(ring):
    a = 0.0
    for i in range(len(ring) - 1):
        a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
    return abs(a) / 2.0


def perp_dist(p, a, b):
    ax, ay = a
    bx, by = b
    px, py = p
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    return ((px - (ax + t * dx)) ** 2 + (py - (ay + t * dy)) ** 2) ** 0.5


def simplify(points, tol):
    """Iterative Douglas-Peucker on an open polyline."""
    n = len(points)
    if n < 3:
        return points
    keep = [False] * n
    keep[0] = keep[-1] = True
    stack = [(0, n - 1)]
    while stack:
        lo, hi = stack.pop()
        best, idx = 0.0, -1
        for i in range(lo + 1, hi):
            d = perp_dist(points[i], points[lo], points[hi])
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack.append((lo, idx))
            stack.append((idx, hi))
    return [p for p, k in zip(points, keep) if k]


def main(src, dst):
    gj = json.load(open(src))
    out = {}
    for feat in gj["features"]:
        name = feat["properties"]["BoroName"]
        geom = feat["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        rings = []
        for poly in polys:
            for ring in poly:
                if ring_area(ring) < MIN_RING_AREA:
                    continue
                pts = [(round(x, 5), round(y, 5)) for x, y in ring[:-1]]
                s = simplify(pts, TOLERANCE)
                if len(s) >= 3:
                    rings.append(s)
        out[name] = rings
    with open(dst, "w") as fh:
        fh.write("# Generated by tools/build_boroughs.py. Do not edit by hand.\n")
        fh.write("# Simplified NYC borough boundaries as (longitude, latitude) rings.\n")
        fh.write("BOROUGH_RINGS = {\n")
        for name in sorted(out):
            fh.write("    %r: [\n" % name)
            for ring in out[name]:
                fh.write("        %r,\n" % (ring,))
            fh.write("    ],\n")
        fh.write("}\n")
    total = sum(len(r) for rings in out.values() for r in rings)
    print("wrote %s: %d rings, %d vertices" % (dst, sum(len(r) for r in out.values()), total))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
